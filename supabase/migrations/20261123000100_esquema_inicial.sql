-- 0001 · Esquema inicial del "Taller de cerámica"
create schema if not exists privado;
revoke all on schema privado from public, anon, authenticated;

create type public.rol_usuario as enum ('admin', 'usuario');
create type public.estado_perfil as enum ('activo', 'bloqueado');
create type public.estado_horario as enum ('disponible', 'bloqueado');
create type public.estado_reserva as enum ('pendiente', 'aprobada', 'reprogramada', 'rechazada', 'cancelada', 'expirada');
create type public.accion_reserva as enum ('solicitada', 'aprobada', 'rechazada', 'reprogramada', 'propuesta_aceptada', 'propuesta_rechazada', 'cancelada', 'expirada');

create table public.salas (
  id uuid primary key default gen_random_uuid(),
  nombre text not null,
  descripcion text,
  zona_horaria text not null default 'America/Bogota',
  capacidad_por_turno int not null default 1 check (capacidad_por_turno > 0),
  calendario_abierto boolean not null default true,
  activa boolean not null default true,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table public.perfiles (
  id uuid primary key references auth.users (id) on delete cascade,
  nombre_completo text not null default '',
  telefono text,
  avatar_url text,
  rol public.rol_usuario not null default 'usuario',
  estado public.estado_perfil not null default 'activo',
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table public.horarios (
  id uuid primary key default gen_random_uuid(),
  sala_id uuid not null references public.salas (id) on delete cascade,
  fecha date not null,
  hora_inicio time not null,
  hora_fin time not null,
  capacidad int not null default 1 check (capacidad > 0),
  estado public.estado_horario not null default 'disponible',
  notas text,
  creado_por uuid references public.perfiles (id),
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  constraint horarios_rango check (hora_fin > hora_inicio),
  constraint horarios_unico unique (sala_id, fecha, hora_inicio, hora_fin)
);
create index horarios_sala_fecha_idx on public.horarios (sala_id, fecha);

create table public.reservas (
  id uuid primary key default gen_random_uuid(),
  sala_id uuid not null references public.salas (id) on delete restrict,
  horario_id uuid not null references public.horarios (id) on delete restrict,
  usuario_id uuid not null references public.perfiles (id) on delete cascade,
  fecha date not null,
  hora_inicio time not null,
  hora_fin time not null,
  estado public.estado_reserva not null default 'pendiente',
  comentario_usuario text,
  comentario_admin text,
  propuesta_fecha date,
  propuesta_hora_inicio time,
  propuesta_hora_fin time,
  token_humano_id uuid,
  resuelto_por uuid references public.perfiles (id),
  resuelto_en timestamptz,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  constraint reservas_rango check (hora_fin > hora_inicio),
  constraint reservas_propuesta_completa check (
    estado <> 'reprogramada'
    or (propuesta_fecha is not null and propuesta_hora_inicio is not null and propuesta_hora_fin is not null)
  )
);
create index reservas_usuario_idx on public.reservas (usuario_id, fecha desc);
create index reservas_horario_idx on public.reservas (horario_id);
create unique index reservas_pendiente_unica_idx on public.reservas (horario_id, usuario_id) where estado = 'pendiente';

create table public.bloqueos_sala (
  id uuid primary key default gen_random_uuid(),
  sala_id uuid not null references public.salas (id) on delete cascade,
  desde timestamptz not null,
  hasta timestamptz not null,
  motivo text,
  creado_por uuid references public.perfiles (id),
  creado_en timestamptz not null default now(),
  constraint bloqueos_rango check (hasta > desde)
);
create index bloqueos_sala_rango_idx on public.bloqueos_sala using gist (tstzrange(desde, hasta));

create table public.reserva_eventos (
  id bigint generated by default as identity primary key,
  reserva_id uuid not null references public.reservas (id) on delete cascade,
  actor_id uuid references public.perfiles (id),
  accion public.accion_reserva not null,
  datos jsonb not null default '{}'::jsonb,
  creado_en timestamptz not null default now()
);
create index reserva_eventos_reserva_idx on public.reserva_eventos (reserva_id);

create table public.adjuntos (
  id uuid primary key default gen_random_uuid(),
  reserva_id uuid not null references public.reservas (id) on delete cascade,
  ruta text not null,
  subido_por uuid not null references public.perfiles (id) on delete cascade,
  creado_en timestamptz not null default now()
);

create table public.retos_humanos (
  id uuid primary key default gen_random_uuid(),
  usuario_id uuid not null references public.perfiles (id) on delete cascade,
  nonce text not null,
  reto jsonb not null,
  respuesta_hash text not null,
  intentos int not null default 0,
  resuelto_en timestamptz,
  expira_en timestamptz not null,
  creado_en timestamptz not null default now()
);
create index retos_humanos_usuario_idx on public.retos_humanos (usuario_id, creado_en desc);
create index retos_humanos_expira_idx on public.retos_humanos (expira_en);

create table public.tokens_humanos (
  id uuid primary key default gen_random_uuid(),
  usuario_id uuid not null references public.perfiles (id) on delete cascade,
  token_hash text not null unique,
  usado_en timestamptz,
  expira_en timestamptz not null,
  creado_en timestamptz not null default now()
);
create index tokens_humanos_usuario_idx on public.tokens_humanos (usuario_id);

alter table public.reservas
  add constraint reservas_token_humano_fk foreign key (token_humano_id)
  references public.tokens_humanos (id) on delete set null;

create table privado.secretos (
  nombre text primary key,
  valor text not null,
  creado_en timestamptz not null default now()
);
