-- 0010 · Correos de reserva (confirmación, solicitud, rechazo y cancelación)
--
-- El envío se hace desde Postgres con `pg_net` contra la API HTTP del proveedor.
-- La clave del proveedor se guarda cifrada en Supabase Vault; aquí solo se leen los
-- ajustes no secretos (proveedor, remitente y copia opcional).
--
-- El correo es una notificación: la reserva no depende de que el proveedor responda.
-- Cada intento queda en `privado.correos_log` para auditoría y para poder reenviarlo
-- desde el panel del administrador.

create extension if not exists pg_net with schema extensions;

create table if not exists privado.correos_log (
  id bigint generated by default as identity primary key,
  reserva_id uuid references public.reservas (id) on delete set null,
  tipo text not null default 'manual'
    check (tipo in ('solicitud', 'confirmacion', 'cancelacion', 'rechazo', 'manual')),
  destinatario text not null,
  asunto text not null,
  html text not null,
  proveedor text,
  request_id bigint,
  estado text not null default 'solicitado'
    check (estado in ('solicitado', 'error', 'enviado')),
  ultimo_error text,
  creado_en timestamptz not null default now()
);

create index if not exists correos_log_reserva_idx
  on privado.correos_log (reserva_id, creado_en desc);

insert into privado.secretos (nombre, valor)
values
  ('correo_proveedor', 'brevo'),
  ('correo_remitente', ''),
  ('correo_remitente_nombre', 'Taller Barro Negro'),
  ('sitio_url', 'https://javierenrique00.github.io/barronegro/')
on conflict (nombre) do nothing;

-- Ajustes no secretos ---------------------------------------------------------
create or replace function privado.configurar_correo(
  p_proveedor text,
  p_remitente text,
  p_nombre text default 'Taller Barro Negro',
  p_copia text default null
) returns void
language plpgsql
security definer
set search_path = privado
as $$
declare
  v_proveedor text := lower(trim(coalesce(p_proveedor, '')));
begin
  if v_proveedor not in ('brevo', 'resend') then
    raise exception 'Proveedor no soportado: %. Usa brevo o resend', p_proveedor;
  end if;
  if p_remitente is null
     or trim(p_remitente) !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$' then
    raise exception 'El remitente debe ser un correo válido';
  end if;

  insert into privado.secretos (nombre, valor)
  values ('correo_proveedor', v_proveedor)
  on conflict (nombre) do update set valor = excluded.valor;

  insert into privado.secretos (nombre, valor)
  values ('correo_remitente', trim(p_remitente))
  on conflict (nombre) do update set valor = excluded.valor;

  insert into privado.secretos (nombre, valor)
  values ('correo_remitente_nombre',
          coalesce(nullif(trim(p_nombre), ''), 'Taller Barro Negro'))
  on conflict (nombre) do update set valor = excluded.valor;

  if p_copia is null or trim(p_copia) = '' then
    delete from privado.secretos where nombre = 'correo_copia';
  else
    insert into privado.secretos (nombre, valor)
    values ('correo_copia', trim(p_copia))
    on conflict (nombre) do update set valor = excluded.valor;
  end if;
end;
$$;

-- Guarda la clave del proveedor en Vault (cifrada). No queda en `privado.secretos`.
create or replace function privado.configurar_api_key_correo(p_api_key text)
returns void
language plpgsql
security definer
set search_path = privado
as $$
declare
  v_id uuid;
  v_clave text := trim(coalesce(p_api_key, ''));
begin
  if length(v_clave) < 10 then
    raise exception 'La API key del correo es demasiado corta';
  end if;

  select id into v_id from vault.secrets where name = 'correo_api_key' limit 1;
  if v_id is null then
    perform vault.create_secret(v_clave, 'correo_api_key',
                                'API key del proveedor de correos de reservas');
  else
    perform vault.update_secret(v_id, v_clave, 'correo_api_key',
                                'API key del proveedor de correos de reservas');
  end if;
end;
$$;

create or replace function privado.correo_api_key()
returns text
language sql
stable
security definer
set search_path = privado
as $$
  select coalesce(
    (select decrypted_secret from vault.decrypted_secrets
      where name = 'correo_api_key' limit 1),
    privado.secreto('correo_api_key')
  );
$$;

-- Llamada HTTP compatible con la instalación de pg_net en `net` o `extensions`.
create or replace function privado.http_post(
  p_url text,
  p_body jsonb,
  p_headers jsonb,
  p_timeout_ms int default 10000
) returns bigint
language plpgsql
security definer
set search_path = public, privado
as $$
declare
  v_schema text;
  v_request bigint;
begin
  select n.nspname into v_schema
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where p.proname = 'http_post'
  order by case when n.nspname = 'net' then 0 else 1 end
  limit 1;

  if v_schema is null then
    raise exception 'pg_net no está instalado';
  end if;

  execute format(
    'select %I.http_post(url := $1, body := $2, headers := $3, timeout_milliseconds := $4)',
    v_schema
  ) into v_request
  using p_url, p_body, p_headers, p_timeout_ms;

  return v_request;
end;
$$;

-- Utilidades de plantilla -----------------------------------------------------
create or replace function privado.escapar_html(p_texto text)
returns text
language sql
immutable
set search_path = pg_catalog
as $$
  select replace(
    replace(
      replace(
        replace(
          replace(coalesce(p_texto, ''), '&', '&amp;'),
          '<', '&lt;'),
        '>', '&gt;'),
      '"', '&quot;'),
    '''', '&#39;');
$$;

create or replace function privado.fecha_larga_es(p_fecha date)
returns text
language sql
immutable
set search_path = pg_catalog
as $$
  select (array['domingo', 'lunes', 'martes', 'miércoles', 'jueves', 'viernes', 'sábado'])
           [extract(dow from p_fecha)::int + 1]
         || ' ' || to_char(p_fecha, 'DD')
         || ' de '
         || (array['enero', 'febrero', 'marzo', 'abril', 'mayo', 'junio',
                   'julio', 'agosto', 'septiembre', 'octubre', 'noviembre', 'diciembre'])
           [extract(month from p_fecha)::int]
         || ' de ' || to_char(p_fecha, 'YYYY');
$$;


-- Plantilla del correo de una reserva ----------------------------------------
create or replace function privado.correo_reserva(
  p_reserva_id uuid,
  p_tipo text
) returns table (destinatario text, asunto text, html text)
language plpgsql
stable
security definer
set search_path = public, privado
as $$
declare
  v public.reservas;
  v_sala text;
  v_fecha text;
  v_hora text;
  v_codigo text;
  v_nombre text;
  v_correo text;
  v_motivo text;
  v_titulo text;
  v_intro text;
  v_extra text;
  v_asunto text;
  v_html text;
  v_sitio text;
begin
  if p_tipo not in ('solicitud', 'confirmacion', 'cancelacion', 'rechazo') then
    raise exception 'Tipo de correo no válido: %', p_tipo;
  end if;

  select * into v from public.reservas where id = p_reserva_id;
  if not found or coalesce(trim(v.correo_contacto), '') = '' then
    return;
  end if;

  v_sala := coalesce(
    (select s.nombre from public.salas s where s.id = v.sala_id),
    'Taller de cerámica'
  );
  v_fecha := privado.fecha_larga_es(v.fecha);
  v_hora := to_char(v.hora_inicio, 'HH24:MI') || ' – ' || to_char(v.hora_fin, 'HH24:MI');
  v_codigo := upper(substr(v.id::text, 1, 8));
  v_nombre := nullif(trim(coalesce(v.nombre_contacto, '')), '');
  v_correo := lower(trim(v.correo_contacto));
  v_motivo := nullif(trim(coalesce(v.comentario_admin, '')), '');
  v_sitio := coalesce(nullif(trim(privado.secreto('sitio_url')), ''),
                      'https://javierenrique00.github.io/barronegro/');

  v_titulo := case p_tipo
    when 'solicitud' then 'Solicitud recibida'
    when 'confirmacion' then 'Reserva confirmada'
    when 'cancelacion' then 'Reserva cancelada'
    else 'Solicitud no confirmada'
  end;

  v_intro := case p_tipo
    when 'solicitud' then
      'Recibimos tu solicitud. El taller la revisará y te avisaremos a este correo cuando quede confirmada.'
    when 'confirmacion' then
      'Tu reserva quedó confirmada. Te esperamos en el taller.'
    when 'cancelacion' then
      case
        when v.resuelto_por is null then 'Tu reserva quedó cancelada a petición tuya.'
        else 'El taller canceló tu reserva.'
      end
    else
      'No pudimos confirmar tu solicitud. Si tienes dudas, responde a este correo.'
  end;

  if v_motivo is not null and p_tipo in ('cancelacion', 'rechazo') then
    v_extra := '<p style="margin:0 0 18px;line-height:1.5"><strong>Motivo:</strong> ' ||
               privado.escapar_html(v_motivo) || '</p>';
  else
    v_extra := '';
  end if;

  v_asunto := case p_tipo
    when 'solicitud' then 'Recibimos tu solicitud · ' || v_fecha || ', ' || to_char(v.hora_inicio, 'HH24:MI')
    when 'confirmacion' then 'Reserva confirmada · ' || v_fecha || ', ' || to_char(v.hora_inicio, 'HH24:MI')
    when 'cancelacion' then 'Reserva cancelada · ' || v_fecha || ', ' || to_char(v.hora_inicio, 'HH24:MI')
    else 'Solicitud no confirmada · ' || v_fecha
  end;

  v_html :=
    '<div style="font-family:Arial,Helvetica,sans-serif;max-width:560px;margin:0 auto;color:#33140a">' ||
    '<div style="background:#8a4b2a;color:#ffffff;padding:20px 24px;border-radius:14px 14px 0 0">' ||
    '<div style="font-size:12px;letter-spacing:.08em;text-transform:uppercase;opacity:.85">' ||
      privado.escapar_html(v_sala) || '</div>' ||
    '<h2 style="margin:6px 0 0;font-size:22px">' || v_titulo || '</h2>' ||
    '</div>' ||
    '<div style="border:1px solid #e7d7ca;border-top:0;padding:24px;border-radius:0 0 14px 14px">' ||
    '<p style="margin:0 0 12px">Hola' ||
      coalesce(', ' || privado.escapar_html(v_nombre), '') || ':</p>' ||
    '<p style="margin:0 0 18px;line-height:1.5">' || v_intro || '</p>' ||
    '<div style="background:#fbf4ee;border-radius:10px;padding:16px;margin:0 0 18px">' ||
    '<p style="margin:0 0 6px"><strong>Fecha:</strong> ' || v_fecha || '</p>' ||
    '<p style="margin:0 0 6px"><strong>Hora:</strong> ' || v_hora || '</p>' ||
    '<p style="margin:0"><strong>Código:</strong> ' || v_codigo || '</p>' ||
    '</div>' ||
    v_extra ||
    '<p style="margin:0 0 8px;font-size:13px;color:#556b5d">Enviamos este mensaje a ' ||
      privado.escapar_html(v_correo) || '.</p>' ||
    '<p style="margin:0;font-size:13px;color:#556b5d">Puedes ver y gestionar esta reserva desde el mismo navegador donde la hiciste, en ' ||
      '<a href="' || privado.escapar_html(v_sitio) || '" style="color:#8a4b2a">la página del taller</a>.</p>' ||
    '</div></div>';

  return query select v_correo, v_asunto, v_html;
end;
$$;

